# ------------------------------------------------------------------------------------------------ exclusive block
def strata3(slots, ctx, stream=False, smoke=False):
    v, _ = strata(slots, ctx, stream=stream)
    v["id"] = "maker3gpu" + v["id"][len("maker"):]
    v.update(stop=["vllm-sub"], gpus=[0, 1, 2],
             strata_config_set={"gpu": [0, 1, 2], "layer_split": "auto"},
             compose=devices([0, 1, 2]), compose_replace=["deploy"])
    v["strata_args_remove"] = v.get("strata_args_remove", []) + ["--trim-stage-weights"]   # needs an explicit split
    if smoke:
        v["smoke"] = True
    return v, "Strata on all three 3090s (#3 on x8 carries the last layers); vllm-sub stopped"


def tp2(mtp=False, smoke=False):
    v = {"id": f"makerB-vllm-tp2-64k{'-mtp' if mtp else ''}", "service": "vllm-sub", "ctx": 64 * K, "slots": 4,
         "stop": ["strata", "llama-guard"], "gpus": [0, 1],
         "args_set": {"--max-model-len": str(64 * K), "--max-num-seqs": "4", "--tensor-parallel-size": "2"},
         "args_add": ["--disable-custom-all-reduce"] + ([VLLM_MTP] if mtp else []),
         "env": {"NCCL_P2P_DISABLE": "1"},
         "compose": devices([0, 1]), "compose_replace": ["deploy"]}
    if smoke:
        v["smoke"] = True
    return v, "scenario B: the 27B AWQ as maker over the two x16 cards; Strata and guard stopped"


def ref(v_note, new_id):
    v = dict(v_note[0]); v["id"] = new_id; v.pop("smoke", None)
    return v, "isolated reference: nothing else runs (size of the parallel queues' interference)"


EXCL = [strata3(2, 64 * K, stream=True, smoke=True), strata3(4, 32 * K), tp2(),        # no MTP: 0 % in vLLM
        ref(MAKER[0], "ref-maker-b4-32k"), ref(SUB_A[0], "ref-subA-awq-32k-s4")]

# ------------------------------------------------------------------------------------------------ workloads
# depth: clients = slots (decode at that depth, no queue) and slots + 2 (queueing); one round each in pass 1 (screening)
DEPTH = {"id": "depth", "kind": "throughput", "fill": [0.25, 0.5, 0.9], "streams": "slots+0,slots+2", "max_tokens": 256,
         "rounds": 1, "corpus": CORPUS}
RAMP = {"id": "ramp", "kind": "throughput", "streams": "ramp+2", "prompt_tokens": 2000, "max_tokens": 256,
        "corpus": CORPUS}


def answerlen(variants, ctx, smoke_variant):
    return {"id": "answerlen", "kind": "tasks", "tasks": "tasks/seed.jsonl", "variants": variants,
            "smoke_variants": [smoke_variant],
            "effort": ["template:low"], "streams": 2, "limit": 6, "max_tokens": ctx - 4096}


GUARD_LOAD = {"id": "guardload", "kind": "throughput", "variants": ["guard-*"], "streams": "ramp+0",
              "prompt_tokens": 1500, "max_tokens": 64, "corpus": CORPUS}


CHECK = "--check" in sys.argv
STALE = []


def write(name, what, gpus, ready, variants, workloads, on_end=None, extra=""):
    end = (f'\non_end = "{on_end}"           # leave the slot empty at the end (ops/bench.yml restores guard, then Strata)'
           if on_end else "")
    out = [HEADER.format(name=name, what=what, gpus=toml(gpus), ready=ready, on_end=end)]
    out += ["\n# " + "-" * 100 + " variants\n"] + [block("variant", v, n) for v, n in variants]
    out += ["\n# " + "-" * 100 + " workloads\n"] + [block("workload", w) for w in workloads]
    if extra:
        out.append(extra)
    f, text = HERE / f"{name}.toml", "\n".join(out)
    if CHECK:
        if not f.is_file() or f.read_text() != text:
            STALE.append(f.name)
    else:
        f.write_text(text)
    return f


def main():
    maker_ws = [dict(DEPTH, variants=["maker-*"]), dict(RAMP, variants=["maker-*"]),
                answerlen(["maker-b4-32k-int8"], 32 * K, "maker-b2-128k-k8v4"), GUARD_LOAD]
    sub_a_ws = [dict(DEPTH), dict(RAMP), answerlen(["subA-awq-32k-s4"], 32 * K, "subA-awq-64k-s1-novis")]
    excl_ws = [dict(DEPTH), dict(RAMP, variants=["ref-*", "makerB-*"])]
    files = [write("p1-maker", "maker queue (Strata #1+#2, guard)", [0, 1], 2400, MAKER + GUARD, maker_ws),
             write("p1-subA", "sub-maker A: vLLM AWQ (#3)", [2], 1800, SUB_A, sub_a_ws)]
    for g, vs in SUB_B.items():
        ws = [dict(DEPTH), dict(RAMP)]
        if any(v["id"] == "subB-iq3s-32k-np3-mtp-g1" for v, _ in vs):
            ws.append(answerlen(["subB-iq3s-32k-np3-mtp-g1"], 32 * K, "subB-iq3s-32k-np3-mtp-g1"))
        files.append(write(f"p1-subB-{g}", f"sub-maker B: llama.cpp IQ3_S in the {vs[0][0]['service']} slot "
                           f"(#{vs[0][0]['gpus'][0] + 1})", vs[0][0]["gpus"], 900, vs, ws,
                           on_end="stop" if g == "g0" else None))
    files.append(write("p1-exclusive", "exclusive block (after both queues)", [0, 1, 2], 2400, EXCL, excl_ws))
    if CHECK:
        if STALE:
            print(f"FAIL: {', '.join(STALE)} differ from gen_phase1.py — run it and commit", file=sys.stderr)
            return 1
        print("ok: bench phase-1 plans are generated from gen_phase1.py")
        return 0
    for f in files:
        print(f"wrote {f.relative_to(HERE.parent.parent.parent)}")


if __name__ == "__main__":
    sys.exit(main())
