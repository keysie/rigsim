"""Writes the benchmark phase 1 plans (docs/bench-plan.md) — one source for the three queues:

  p1-maker.toml      maker queue: Strata on 3090 #1+#2 (+ the guard on #2)          } group 1, in parallel
  p1-subA.toml       sub-maker A: vLLM AWQ on 3090 #3                                 }
  p1-subB-g0/g1/g2   sub-maker B: the llama.cpp IQ3_S grid split over all three cards — in Strata's slot (#1),
                     the guard's slot (#2) and vllm-sub's (#3); group 2, Strata and guard stopped first (user 2026-10-21)
  p1-exclusive.toml  group 3, alone: Strata on 3 cards, vLLM 27B over #1+#2 (scenario B), isolated references

Smoke (`benchq --smoke`, `ops/bench.yml -e bench_run=smoke`): only the variants marked smoke=True below — one per
mechanism — with one short request per workload.

Edit the tables here, run `python3 infra/bench/plans/gen_phase1.py`, commit the .toml files with it (precommit checks
that they are up to date). Slot counts that do not fit simply fail to start and are skipped (reason in the report).
"""
